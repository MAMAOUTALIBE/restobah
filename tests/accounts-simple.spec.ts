async function requestResetLinkForSignedInCustomer(page:Page,email:string,directory:string){
  const csrf=(await page.context().cookies()).find(cookie=>cookie.name==='csrftoken')?.value;
  expect(csrf).toBeTruthy();
  const response=await page.request.post('/api/auth/password-reset/',{headers:{'X-CSRFToken':csrf!},data:{email}});
  expect(response.ok()).toBe(true);
  let link='';
  await expect.poll(()=>{
    const content=readdirSync(directory).map(file=>readFileSync(join(directory,file),'utf8')).find(body=>body.includes(email)&&body.includes('reset_uid='));
    link=content?.match(/https?:\/\/[^\s<>]*\?reset_uid=[^\s<>]+/)?.[0]||'';
    return link;
  }).not.toBe('');
  return link;
}

